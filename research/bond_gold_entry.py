def dividend_block():
    """分红机制答疑：复投还是拿现金／除息日净值为什么跌／要不要等除息后再买"""
    L = []
    A = L.append
    r = load_raw(MAIN_BOND) if MAIN_BOND else None
    A("## 十、关于分红的三个问题（会这么想的人很多，但答案是反直觉的）")
    A("")
    if not r:
        A("（缺少原始净值数据，本节跳过）")
        return "\n".join(L)
    ks, unit, tr, div = r
    # 1) 恒等式：净值变化 + 每份分红 = 市场涨跌
    ok = tot = 0
    for k in ks:
        if k not in div:
            continue
        i = ks.index(k)
        if i == 0:
            continue
        per = div[k]
        lhs = unit[k] - unit[ks[i - 1]] + per
        rhs = unit[ks[i - 1]] * (tr[k] / tr[ks[i - 1]] - 1)
        tot += 1
        if abs(lhs - rhs) < 0.0005:
            ok += 1
    cum_div = sum(div.values())
    A("### 10.1 分红后净值跌了，我是亏了吗？——不是，那是分红本身")
    A("")
    A("**关键恒等式**（以 007172 %s 为例，逐次除息日验证）：" % "易方达中债3-5年国开债C")
    A("")
    A("```")
    A("  单位净值变化  +  每份分红  =  前一日净值 × 当日市场涨跌")
    A("```")
    A("")
    A("拿 2020-01-09 那次（每 10 份派 0.12 元）实测：")
    A("")
    A("| 项 | 数值 |")
    A("|---|---|")
    A("| 前一日单位净值 | 1.0178 |")
    A("| 除息日单位净值 | 1.0062（跌 0.0116）|")
    A("| 每份分红 | 0.0120 |")
    A("| 净值变化 + 分红 | **+0.0004** |")
    A("| 当日真实涨跌（1.0178 × +0.04%）| **+0.0004** ✅ |")
    A("")
    A("**除息日净值跌的部分，一分不少地变成了你的分红。** 全序列 %d 次分红，恒等式成立 **%d 次**。"
      % (tot, ok))
    A("")
    A("成立以来的完整对账最能说明问题：")
    A("")
    A("| 项 | 数值 |")
    A("|---|---|")
    A("| 每份累计分红 | **%.4f 元** |" % cum_div)
    A("| 单位净值变化 | +%.4f 元（几乎没动）|" % (unit[ks[-1]] - unit[ks[0]]))
    A("| 累计净值变化 | +%.4f 元 |" % (unit[ks[-1]] + cum_div - unit[ks[0]]))
    A("")
    A("**这只债基成立以来的收益，%.0f%% 来自分红，只有 %.0f%% 来自净值上涨。**"
      % (100 * cum_div / (unit[ks[-1]] - unit[ks[0]] + cum_div),
         100 * (unit[ks[-1]] - unit[ks[0]]) / (unit[ks[-1]] - unit[ks[0]] + cum_div)))
    A("所以**千万别用「单位净值涨了多少」判断赚没赚**——那会得出「债基六年只涨 1.6%」的错觉。")
    A("")
    A("### 10.2 分红是复投还是拿现金？")
    A("")
    A("**两种方式都由你设置，默认通常是「现金分红」，要在 App 里手动改成「红利再投资」。**")
    A("")
    A("| | 现金分红（默认） | 红利再投资 |")
    A("|---|---|---|")
    A("| 拿到什么 | 现金打进账户 | 自动按除息后净值买成份额 |")
    A("| 份额 | 不变 | 增加 |")
    A("| 后续复利 | **靠你自己手动再买回去** | 自动滚入 |")
    A("| 适合 | 要靠分红当现金流 | **长期持有、不需要现金流** |")
    A("")
    A("**对你这种「债腿长期放着当减震器」的用法，应该设成「红利再投资」**——")
    A("否则每季度收到几十块现金躺在账户里，既没收益，你还得记着手动买回去。")
    A("（个人投资者从基金分红取得的收益**免征所得税**，所以两种方式不存在税负差别，")
    A("纯看你要不要这笔现金流。）")
    A("")
    A("### 10.3 「等分红除息后再买入」是不是更划算？——不是")
    A("")
    A("这是最经典的错觉：看到净值从 1.0178 掉到 1.0062，就觉得「等它跌完再买，能买到更多份」。")
