def load(code):
    """读场外基金**总收益指数**（分红再投，tr）或指数收盘（无 tr 时退化到 nav）。

    2026-09-17 修正：此前用的是累计净值(LJJZ)，它虽含分红但只「简单相加」，
    比分红再投资的真实收益低（007172 差 0.35pp/年、161603 差 1.21pp/年）。
    现优先用 `tr`（官方日增长率复利，已验证除息日已做分红调整）。
    """
    p = os.path.join(NAVD, code + ".json")
    if not os.path.exists(p):
        return None
    j = json.load(open(p, encoding="utf-8"))
    d = j.get("tr") or j.get("nav")
    ks = sorted(d)
    return ks, [d[k] for k in ks]


def load_raw(code):
    """读原始明细：单位净值 / 总收益指数 / 每份分红（供分红机制答疑用）"""
    p = os.path.join(NAVD, code + ".json")
    if not os.path.exists(p):
        return None
    j = json.load(open(p, encoding="utf-8"))
    raw = j.get("unit") or {}
    tr = j.get("tr") or {}
    dv = {k: float(v) for k, v in (j.get("div") or {}).items()}
    ks = sorted(set(raw) & set(tr))
    if len(ks) < 300:
        return None
    return ks, {k: raw[k] for k in ks}, {k: tr[k] for k in ks}, dv


def bucket_signal(ks, v, edges_fns):
    """三种信号 -> 分档未来1年收益中位"""
    out = []
    for name, fn, edges in edges_fns:
        data = []
        for i in range(len(v)):
            if i + FWD >= len(v):
                continue
            s = fn(v, i)
            if s is not None:
                data.append((s, v[i + FWD] / v[i] - 1))
        if len(data) < FWD + 100:
            continue
        buckets, lo = [], -9e9
        for e, nm in edges:
            sub = [f for s, f in data if lo < s <= e]
            if len(sub) >= 30:
                buckets.append((nm, len(sub), st.median(sub) * 100))
            lo = e
        if len(buckets) >= 2:
            out.append((name, buckets))
    return out


def dd_fn(n):
    return lambda v, i: (v[i] / max(v[max(0, i + 1 - n):i + 1]) - 1) if i + 1 >= n else None


def dev_fn(v, i):
    return (v[i] / (sum(v[i + 1 - MA:i + 1]) / MA) - 1) if i + 1 >= MA else None


def mom_fn(v, i):
    return (v[i] / v[i - 250] - 1) if i >= 250 else None


