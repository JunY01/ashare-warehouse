def wait_vs_now(ks, v, X, maxwait=250, lb=250):
    """立刻买 vs 等回撤≥X%再买（各持有1年）"""
    A, B, waits = [], [], []
    for s in range(lb, len(v) - 1):
        A.append(v[min(s + 250, len(v) - 1)] / v[s] - 1)
        bought = None
        for t in range(s, min(s + maxwait, len(v) - 1)):
            if v[t] / max(v[t + 1 - lb:t + 1]) - 1 <= -X:
                bought = t
                break
        if bought is None:
            bought = min(s + maxwait, len(v) - 1)
            waits.append(maxwait)
        else:
            waits.append(bought - s)
        B.append(v[min(bought + 250, len(v) - 1)] / v[bought] - 1)
    return st.mean(A) * 100, st.mean(B) * 100, (st.mean(B) - st.mean(A)) * 100, st.mean(waits)


def lump_vs_dca(ks, v, T):
    """一次性 vs 分T批：平均、分批赢率、各自最坏"""
    L, D = [], []
    for s in range(0, len(v) - T - 250):
        end = min(s + T, len(v) - 1)
        e2 = min(end + 250, len(v) - 1)
        L.append((v[e2] / v[s] - 1) * 100)
        buys = [v[min(s + t, len(v) - 1)] for t in range(T)]
        D.append(st.mean([v[e2] / b - 1 for b in buys]) * 100)
    if not L:
        return None
    wr = 100.0 * sum(1 for a, b in zip(L, D) if b > a) / len(L)
    return st.mean(L), st.mean(D), wr, min(L), min(D)


def stats_of(ks, v):
    yrs = len(ks) / 250.0
    ann = (v[-1] / v[0]) ** (1 / yrs) - 1
    r1 = [v[i + 250] / v[i] - 1 for i in range(len(v) - 250)]
    pk, dd = v[0], 0.0
    for x in v:
        pk = max(pk, x)
        dd = min(dd, x / pk - 1)
    return ann * 100, min(r1) * 100, dd * 100


def cur_of(ks, v):
    i = len(v) - 1
    return dict(date=ks[i], dd=(v[i] / max(v[max(0, i + 1 - 250):i + 1]) - 1) * 100,
                dev=(v[i] / (sum(v[i + 1 - MA:i + 1]) / MA) - 1) * 100 if i + 1 >= MA else None,
                mom=(v[i] / v[i - 250] - 1) * 100 if i >= 250 else None,
                pct=100.0 * sum(1 for x in v if x <= v[i]) / len(v))


