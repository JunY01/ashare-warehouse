def account():
    """从 config/positions.json 读股票类持仓与现金（唯一真身，不硬编码）"""
    p = os.path.join(CONFIG_ROOT, "positions.json")
    if not os.path.exists(p):
        return None
    try:
        j = json.load(open(p, encoding="utf-8"))
        eq = sum(x.get("市值", 0) for x in j.get("资金A", {}).get("基金", []))
        eq += sum(x.get("市值", 0) for x in j.get("资金B", {}).get("底仓", {}).get("配置", []) if x.get("市值"))
        cash = j.get("资金A", {}).get("账户现金", {}).get("金额", 0)
        return dict(equity=eq, cash=cash, pool=eq + cash)
    except (KeyError, ValueError, TypeError):
        return None



